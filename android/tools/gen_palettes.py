"""Generate Nacre's fixed palettes as Material 3 color schemes (Kotlin) from HCT tonal palettes.

    python3 -m venv /tmp/mcu && /tmp/mcu/bin/pip install materialyoucolor
    /tmp/mcu/bin/python android/tools/gen_palettes.py > android/app/src/main/java/com/ryderdavid/nacre/ui/theme/Palettes.kt

Every fixed palette, Pearl (the default) included, are hue and chroma per tonal palette:
primary, secondary, tertiary, neutral and neutral variant. Tones follow the M3 color roles.
"""
from materialyoucolor.palettes.tonal_palette import TonalPalette

PALETTES = {
    # Pearl: Nacre's own mother-of-pearl teal, lilac and clay (measured from the original hand-made scheme).
    "Pearl":  ((202, 40), (294, 24), (44, 36), (213, 5), (205, 8)),
    "Ocean":  ((268, 56), (250, 24), (236, 44), (258, 6), (255, 12)),   # blues throughout
    "Sage":   ((140, 36), (125, 16), (190, 26), (130, 4), (130, 8)),
    "Ember":  ((42, 60),  (48, 20),  (80, 38),  (45, 6),  (45, 10)),
    "Orchid": ((330, 44), (318, 18), (15, 34),  (320, 5), (320, 10)),
}

LIGHT = [("primary", "P", 40), ("onPrimary", "P", 100), ("primaryContainer", "P", 90), ("onPrimaryContainer", "P", 30),
         ("inversePrimary", "P", 80),
         ("secondary", "S", 40), ("onSecondary", "S", 100), ("secondaryContainer", "S", 90), ("onSecondaryContainer", "S", 30),
         ("tertiary", "T", 40), ("onTertiary", "T", 100), ("tertiaryContainer", "T", 90), ("onTertiaryContainer", "T", 30),
         ("background", "N", 98), ("onBackground", "N", 10), ("surface", "N", 98), ("onSurface", "N", 10),
         ("surfaceVariant", "NV", 90), ("onSurfaceVariant", "NV", 30), ("surfaceTint", "P", 40),
         ("inverseSurface", "N", 20), ("inverseOnSurface", "N", 95), ("outline", "NV", 50), ("outlineVariant", "NV", 80),
         ("surfaceBright", "N", 98), ("surfaceDim", "N", 87),
         ("surfaceContainerLowest", "N", 100), ("surfaceContainerLow", "N", 96), ("surfaceContainer", "N", 94),
         ("surfaceContainerHigh", "N", 92), ("surfaceContainerHighest", "N", 90)]
DARK = [("primary", "P", 80), ("onPrimary", "P", 20), ("primaryContainer", "P", 30), ("onPrimaryContainer", "P", 90),
        ("inversePrimary", "P", 40),
        ("secondary", "S", 80), ("onSecondary", "S", 20), ("secondaryContainer", "S", 30), ("onSecondaryContainer", "S", 90),
        ("tertiary", "T", 80), ("onTertiary", "T", 20), ("tertiaryContainer", "T", 30), ("onTertiaryContainer", "T", 90),
        ("background", "N", 6), ("onBackground", "N", 90), ("surface", "N", 6), ("onSurface", "N", 90),
        ("surfaceVariant", "NV", 30), ("onSurfaceVariant", "NV", 80), ("surfaceTint", "P", 80),
        ("inverseSurface", "N", 90), ("inverseOnSurface", "N", 20), ("outline", "NV", 60), ("outlineVariant", "NV", 30),
        ("surfaceBright", "N", 24), ("surfaceDim", "N", 6),
        ("surfaceContainerLowest", "N", 4), ("surfaceContainerLow", "N", 10), ("surfaceContainer", "N", 12),
        ("surfaceContainerHigh", "N", 17), ("surfaceContainerHighest", "N", 22)]

def scheme(name, spec, roles, fn):
    pals = dict(zip(["P", "S", "T", "N", "NV"], (TonalPalette.from_hue_and_chroma(h, c) for h, c in spec)))
    args = ",\n".join("    %s = Color(0xFF%06X)" % (r, pals[p].tone(t) & 0xFFFFFF) for r, p, t in roles)
    return "internal val %s = %s(\n%s,\n)\n" % (name, fn, args)

def swatch(spec):
    P, S, T = (TonalPalette.from_hue_and_chroma(h, c) for h, c in spec[:3])
    return "listOf(Color(0xFF%06X), Color(0xFF%06X), Color(0xFF%06X))" % (P.tone(40) & 0xFFFFFF, S.tone(70) & 0xFFFFFF, T.tone(60) & 0xFFFFFF)

out = ["// Generated by android/tools/gen_palettes.py from HCT tonal palettes. Do not edit by hand.",
       "package com.ryderdavid.nacre.ui.theme", "",
       "import androidx.compose.material3.darkColorScheme",
       "import androidx.compose.material3.lightColorScheme",
       "import androidx.compose.ui.graphics.Color", ""]
for name, spec in PALETTES.items():
    out.append(scheme(name + "Light", spec, LIGHT, "lightColorScheme"))
    out.append(scheme(name + "Dark", spec, DARK, "darkColorScheme"))
out.append("/** Primary, secondary and tertiary swatch colors for the picker. */")
out.append("internal val GeneratedSwatches = mapOf(\n%s,\n)" % ",\n".join('    "%s" to %s' % (n, swatch(s)) for n, s in PALETTES.items()))
print("\n".join(out))
